const now = Date.now()
const DAY = 86400000

/**
 * 一条示例记忆。字段与 meow 适配器读出来的原始节点保持一致。
 * @param {string} id
 * @param {[string,string]} ws [slug, 显示名]
 */
function mem(id, ws, level, title, content, keywords, importance, days, hits, extra = {}) {
  return {
    id,
    uid: id,
    provider: 'demo',
    adapter: 'demo',
    ws: ws[0],
    wsTitle: ws[1],
    level,
    title,
    label: title,
    content,
    project: extra.project || ws[1],
    subcategory: extra.subcategory || null,
    goal: extra.goal || null,
    keywords,
    importance,
    status: extra.status || 'active',
    hits,
    createdAt: now - days * DAY,
    updatedAt: now - (extra.updatedDays == null ? days : extra.updatedDays) * DAY,
    accessedAt: hits > 0 ? now - Math.min(days, 2) * DAY : null,
    sessionId: extra.sessionId || null,
  }
}

