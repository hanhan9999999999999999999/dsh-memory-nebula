const LONG_SQLITE = `为什么星港的数据格式最后选了 SQLite，而不是把笔记存成一堆 JSON 文件。

一、写入原子性。笔记应用最怕的是「写了一半断电」，JSON 文件要么整份重写、要么留下半截；SQLite 的 WAL 让一次写入要么完整可见、要么完全不存在，这对本地优先的产品是底线。

二、查询。想做「这个标签下最近改过的 20 条」，JSON 方案得把整个目录读进内存再排序；SQLite 一条带索引的 SQL 就够了。星港的索引文件叫 \`xingang.idx\`，里面就是 FTS5 的全文索引。

三、迁移。schema 变更用 migration 脚本按版本号顺序跑，失败就回滚；JSON 方案要自己写「读到旧字段怎么办」的兼容层，半年后没人敢动。

四、代价。SQLite 不是零成本：并发写要靠单写者队列，跨进程要小心锁；移动端还要处理 WAL 文件随包拷贝的问题。所以星港的规则是——只有一个写进程，其它进程只读。

五、不选 LevelDB / RocksDB 的原因：它们适合 KV，不适合「按标签、按时间、按全文」这种关系型查询；而且原生依赖会让「单文件二进制」的发布方式变复杂。

结论：SQLite 作为唯一真相源，导出功能负责把数据还成人类可读的 Markdown。迁移脚本必须和 schema 版本一起进仓库，任何一次发布前都要在旧库副本上跑一遍。

补充（2026-11 复盘）：真正麻烦的是「用户在不同版本之间来回装」。降级安装会碰到「库比程序新」的表结构，程序不认识新列，直接报错。现在的策略是启动时先读 schema 版本：比程序新就拒绝写入、只允许导出，提示「请升级到更新版本，或先导出备份」。这条规则写进了发布检查清单，比任何迁移脚本都重要——迁移能补数据，补不回用户的信任。`

