  const params = new URLSearchParams(location.search)
  const queryLang = params.get('lang')
  let lang = queryLang === 'en' || queryLang === 'zh' ? queryLang : null
  if (!lang) {
    try {
      lang = localStorage.getItem('nebula.lang')
    } catch {}
  }
  if (lang !== 'en' && lang !== 'zh') {
    lang = String(navigator.language || '').toLowerCase().startsWith('zh') ? 'zh' : 'en'
  }

  function t(zh, vars) {
    let s = lang === 'en' ? EN[zh] || zh : zh
    if (vars) for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]))
    return s
  }

  function applyDom(root) {
    const scope = root || document
    document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN'
    document.documentElement.classList.toggle('lang-en', lang === 'en')
    const title = document.querySelector('title')
    if (title) title.textContent = lang === 'en' ? 'Memory Nebula' : '记忆星图 · Memory Nebula'
    const desc = document.querySelector('meta[name="description"]')
    if (desc && lang === 'en') {
      desc.setAttribute('content', 'Turn memories scattered across workspaces into a map of evidence: see them, walk the links, take it with you.')
    }
    for (const el of scope.querySelectorAll('[data-zh]')) {
      const key = el.getAttribute('data-zh')
      if (key != null) el.textContent = t(key)
    }
    for (const el of scope.querySelectorAll('[data-zh-title]')) {
      const key = el.getAttribute('data-zh-title')
      if (key != null) el.setAttribute('title', t(key))
    }
    for (const el of scope.querySelectorAll('[data-zh-ph]')) {
      const key = el.getAttribute('data-zh-ph')
      if (key != null) el.setAttribute('placeholder', t(key))
    }
    for (const el of scope.querySelectorAll('[data-zh-aria]')) {
      const key = el.getAttribute('data-zh-aria')
      if (key != null) el.setAttribute('aria-label', t(key))
    }
    for (const el of scope.querySelectorAll('[data-lang-label]')) el.textContent = lang === 'en' ? '中' : 'EN'
  }

  function setLang(next) {
    try {
      localStorage.setItem('nebula.lang', next)
    } catch {}
    location.reload()
  }

  const api = {
    t,
    applyDom,
    setLang,
    get lang() {
      return lang
    },
    toggle() {
      setLang(lang === 'en' ? 'zh' : 'en')
    },
  }
  window.NebulaI18n = api
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', () => applyDom())
  else applyDom()
